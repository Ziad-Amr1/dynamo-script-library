#!/usr/bin/env python3
"""Generate the tool catalog inside the root README.

The catalog is written between two HTML comment markers configured in
``.github/scripts-catalog.yml``. Everything outside the markers is preserved.

Usage:
    python tools/generate_catalog.py
    python tools/generate_catalog.py --check
    python tools/generate_catalog.py --stdout

``--check`` exits with status 1 when the README catalog is stale, which is what
CI uses. The output is deterministic: tools are sorted by name and categories
follow the order in the configuration file.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from _common import (
    CatalogConfig,
    LibraryError,
    Tool,
    discover_tools,
    find_root,
    load_config,
)


def _escape_cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ").strip()


def _render_tool_table(tools: list[Tool], config: CatalogConfig) -> list[str]:
    lines = [
        "| Tool | Description | Version | Engine | Status |",
        "| --- | --- | --- | --- | --- |",
    ]
    for tool in tools:
        name = _escape_cell(tool.name)
        description = _escape_cell(tool.description)
        version = tool.version.replace("`", "")
        engine = _escape_cell(str(tool.manifest.get("python_engine", "N/A")))
        status = _escape_cell(config.status_label(tool.status))
        lines.append(
            f"| [{name}]({tool.readme_link()}) | {description} | "
            f"`{version}` | {engine} | {status} |"
        )
    return lines


def render_catalog(tools: list[Tool], config: CatalogConfig) -> str:
    """Return the Markdown body for the generated catalog section."""
    used_categories = {tool.category for tool in tools}
    category_count = len([c for c in config.category_ids if c in used_categories])
    lines = [
        "<!-- This section is generated by tools/generate_catalog.py. Do not edit by hand. -->",
        "",
    ]
    if not tools:
        lines.extend(
            [
                "No tools are registered yet. Add a tool folder under "
                "`scripts/<category>/<tool-id>/` with a `script.json` manifest, "
                "then run `python tools/generate_catalog.py`.",
            ]
        )
        return "\n".join(lines)

    tool_word = "tool" if len(tools) == 1 else "tools"
    category_word = "category" if category_count == 1 else "categories"
    lines.extend(
        [
            f"**{len(tools)} {tool_word}** in **{category_count} {category_word}**. "
            "Full requirements and verified compatibility are documented in each tool README.",
            "",
        ]
    )

    for category in config.categories:
        category_id = category["id"]
        category_tools = sorted(
            (tool for tool in tools if tool.category == category_id),
            key=lambda tool: tool.name.casefold(),
        )
        if not category_tools:
            continue
        lines.append(f"### {category.get('name', category_id)}")
        lines.append("")
        if category.get("description"):
            lines.append(f"_{_escape_cell(str(category['description']))}_")
            lines.append("")
        lines.extend(_render_tool_table(category_tools, config))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def replace_catalog(readme_text: str, config: CatalogConfig, body: str) -> str:
    start = config.catalog_start
    end = config.catalog_end
    start_index = readme_text.find(start)
    end_index = readme_text.find(end)
    if start_index == -1 or end_index == -1 or end_index < start_index:
        raise LibraryError(
            f"Could not find the catalog markers in {config.readme}. "
            f"Expected '{start}' before '{end}'."
        )
    before = readme_text[: start_index + len(start)]
    after = readme_text[end_index:]
    return f"{before}\n{body}\n{after}"


def build_expected_readme(root: Path, config: CatalogConfig) -> tuple[Path, str]:
    readme_path = root / config.readme
    try:
        original = readme_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise LibraryError(f"Cannot read {readme_path}: {exc}") from exc
    tools = discover_tools(root, config)
    expected = replace_catalog(original, config, render_catalog(tools, config))
    return readme_path, expected


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help="Repository root. Defaults to the nearest parent with .github/scripts-catalog.yml.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with status 1 if the README catalog is out of date.",
    )
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="Print the generated catalog instead of writing the README.",
    )
    args = parser.parse_args(argv)

    try:
        root, config = load_config(find_root(args.root))
        readme_path, expected = build_expected_readme(root, config)
    except LibraryError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        tools = discover_tools(root, config)
        print(render_catalog(tools, config), end="")
        return 0

    current = readme_path.read_text(encoding="utf-8")
    if current == expected:
        print("Catalog is up to date.")
        return 0
    if args.check:
        print(
            "error: the README catalog is out of date. "
            "Run 'python tools/generate_catalog.py' and commit the result.",
            file=sys.stderr,
        )
        return 1

    readme_path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Updated {readme_path}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
